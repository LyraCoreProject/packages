local protocol = WaveDefense
local passed = 0
local function test(name, run)
    run()
    passed = passed + 1
    print("PASS " .. name)
end
local function status(phase, match, request, pending, revision)
    return "v1|" .. (phase or "lobby") .. "|" .. (match or "0") .. "|5|20|350|400|8400|10000|12|24|12500|" .. (pending or "0") .. "|3|0|8|42|" .. (request or "0") .. "|" .. (revision or "0")
end
local function reply(action, payload)
    return "v1|package.wave_defense." .. action .. ".result|0|1/1|" .. payload
end
local function newClient()
    local sent, saved = {}, {}
    local client = protocol.NewClient(function(message) table.insert(sent, message) end, function(request) table.insert(saved, request) end)
    client:Connect(0, "0")
    return client, sent, saved
end
local function receive(client, action, payload, now)
    return client:Receive("STC", reply(action, payload), "UNKNOWN", "Kara", "Kara", now or 0)
end
local function synchronize(client, payload, now)
    client:Tick(now or 0)
    assert(receive(client, "status", payload or status(), now or 0))
end

test("u64 identifiers never pass through Lua numbers", function()
    assert(protocol.Increment("9007199254740991") == "9007199254740992")
    assert(protocol.Increment("9999999999999999999") == "10000000000000000000")
    assert(protocol.Increment("18446744073709551614") == "18446744073709551615")
    assert(not protocol.Increment("18446744073709551615"))
    assert(not protocol.Decimal("18446744073709551616"))
    assert(not protocol.Decimal("01"))
    assert(not protocol.Decimal("1e5"))
    assert(not protocol.Decimal(5))
    assert(protocol.Greater("10", "9"))
end)

test("documented status fields retain their meaning", function()
    local parsed = protocol.Status(status("preparation", "9007199254740993", "9007199254740995", "2", "9"))
    assert(parsed.match == "9007199254740993")
    assert(parsed.lastRequest == "9007199254740995")
    assert(parsed.phase == "preparation" and parsed.wave == 5 and parsed.level == 20)
    assert(parsed.baseHP == 8400 and parsed.baseMax == 10000 and parsed.enemies == 12)
    assert(parsed.gold == 12500 and parsed.pending == 2 and parsed.readyCount == 3 and parsed.queueSeconds == 42)
    assert(parsed.revision == "9")
    assert(not protocol.Status(status() .. "|extra"))
    assert(not protocol.Status(string.gsub(status(), "lobby", "unknown")))
    assert(not protocol.Status(string.gsub(status(), "8400", "10001")))
end)

test("offers and roster require bounded complete fields", function()
    local offer = protocol.Offer("v1|123|9|20|2|7|talent|Ice Shards|All five ranks|8|spell|Frost Nova|Ranks grow with level|9|spell|Blizzard|Area damage")
    assert(offer and table.getn(offer.choices) == 3 and offer.choices[1].id == "7")
    assert(not protocol.Offer("v1|123|9|20|2|7|talent|Ice Shards"))
    assert(not protocol.Offer("v1|123|9|20|2|7|gear|Sword|Damage"))
    assert(not protocol.Offer("v1|123|9|20|2|7|spell|Nova|A|7|spell|Nova|A"))
    local roster = protocol.Roster("v1|9007199254740993|Brann Bot|tank|1|1|41|Kara|damage|0|0")
    assert(roster and roster[1].bot and not roster[2].bot and not roster[2].ready)
    assert(not protocol.Roster("v1|41|Kara|damage|2|0"))
    assert(not protocol.Roster("v1|41|Kara|damage|0|0|41|Kara|damage|0|0"))
    assert(not protocol.Roster("v1|41|Kara\nInjected|damage|0|0"))
end)

test("envelopes enforce family, version, parts and payload cap", function()
    local action, payload = protocol.Reply(reply("status", status()))
    assert(action == "status" and payload == status())
    assert(not protocol.Reply("v1|package.other.status.result|0|1/1|v1"))
    assert(not protocol.Reply(string.gsub(reply("status", "v1"), "1/1", "1/2")))
    assert(not protocol.Reply(reply("offer", string.rep("x", 1025))))
    assert(not protocol.Reply(reply("offer", "v1\000")))
    assert(protocol.Request("choose", "2", "9007199254740993|123|9|7") == "v1||package.wave_defense.choose||2||1/1||9007199254740993||123||9||7")
end)

test("private replies from other Characters cannot update state", function()
    local client = newClient()
    client:Tick(0)
    assert(not client:Receive("STC", reply("status", status()), "UNKNOWN", "Another", "Kara", 0))
    assert(not client:Receive("STC", reply("status", status()), "PARTY", "Kara", "Kara", 0))
    assert(not client:Receive("OTHER", reply("status", status()), "UNKNOWN", "Kara", "Kara", 0))
    assert(not client.status and client.inflight)
    assert(receive(client, "status", status(), 0))
end)

test("polling never overlaps and a timeout never repeats a Durable Request", function()
    local client, sent = newClient()
    client:Tick(0)
    client:Tick(2)
    client:Tick(5.9)
    assert(table.getn(sent) == 1)
    assert(receive(client, "status", status(), 5.9))
    assert(client:Act("select", { "8" }, 5.9))
    assert(not client:Act("queue", {}, 6))
    client:Tick(7)
    client:Tick(11.9)
    assert(table.getn(sent) == 3)
    assert(string.find(sent[3], "wave_defense.status", 1, true))
    assert(not client.synced and not client:Act("queue", {}, 12))
end)

test("request counter resumes above durable status and persists before send", function()
    local client, sent, saved = newClient()
    synchronize(client, status("lobby", "0", "9007199254740993"))
    assert(saved[1] == "9007199254740993")
    assert(client:Act("select", { "8" }, 0))
    assert(saved[2] == "9007199254740994")
    assert(string.find(sent[2], "9007199254740994||8", 1, true))
    assert(not client.synced)
    assert(receive(client, "select", status("lobby", "0", "9007199254740994"), 0.1))
    assert(client.synced)
end)

test("late replies cannot confirm a newer Durable Request", function()
    local client = newClient()
    synchronize(client)
    assert(client:Act("select", { "8" }, 0))
    assert(not receive(client, "select", status(), 0.1))
    assert(not client.synced and client.inflight)
    assert(receive(client, "select", status("lobby", "0", "1"), 0.2))
    client:Tick(2.2)
    assert(not receive(client, "status", status(), 2.3))
    assert(client.status.lastRequest == "1")
end)

test("Refused leaves status intact and forces a fresh read", function()
    local client, sent = newClient()
    synchronize(client)
    assert(client:Act("queue", {}, 0))
    assert(receive(client, "queue", "Refused|Every human must consent", 0.1))
    assert(client.status.phase == "lobby" and not client.synced)
    assert(client.notice == "Every human must consent")
    client:Tick(2)
    assert(string.find(sent[3], "wave_defense.status", 1, true))
    assert(receive(client, "status", status(), 2.1))
    assert(client.notice == "Every human must consent")
end)

test("disabled mode backs off without queuing requests", function()
    local client, sent = newClient()
    client:Tick(0)
    assert(receive(client, "status", "Refused|Wave Defense is disabled", 0))
    client:Tick(2)
    client:Tick(9)
    assert(table.getn(sent) == 1 and not client.synced)
    client:Tick(10)
    assert(table.getn(sent) == 2)
end)

test("choices use the exact offer and clear on combat or round reset", function()
    local client, sent = newClient()
    synchronize(client, status("preparation", "123", "0", "2", "9"))
    client:Tick(0.1)
    assert(receive(client, "offer", "v1|123|9|20|2|7|talent|Ice Shards|All five ranks", 0.2))
    assert(not client:Act("choose", { "123", "8", "7" }, 0.3))
    assert(not client:Act("choose", { "123", "9", "8" }, 0.3))
    assert(client:Act("choose", { "123", "9", "7" }, 0.3))
    assert(client.status.pending == 2)
    assert(not client:Act("choose", { "123", "9", "7" }, 0.4))
    assert(receive(client, "choose", status("preparation", "123", "1", "1", "10"), 0.5))
    assert(not client.offer)
    synchronize(client, status("combat", "123", "1", "1", "10"), 2.5)
    assert(not client.offer and not client:Act("choose", { "123", "9", "7" }, 2.5))
    synchronize(client, status("lobby", "0", "1"), 4.5)
    assert(not client.offer and not client.roster)
end)

test("hidden roster and combat rewards cause no extra reads", function()
    local client, sent = newClient()
    synchronize(client)
    client.visible = false
    client:Tick(0.2)
    client:Tick(1.9)
    assert(table.getn(sent) == 1)
    synchronize(client, status("combat", "123", "0", "2", "9"), 2)
    client.visible = true
    client:Tick(2.2)
    assert(table.getn(sent) == 2)
end)

test("disconnect blocks actions and reconnect resumes SavedVariables", function()
    local client = newClient()
    synchronize(client)
    client:Disconnect()
    assert(not client:Act("queue", {}, 1))
    client:Connect(2, "9007199254740999")
    synchronize(client, status(), 2)
    assert(client.request == "9007199254740999")
    assert(client:Act("select", { "8" }, 2))
    assert(client.request == "9007199254741000")
end)

